import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {createHash} from 'node:crypto';
import {classify} from './model.mjs';
const here=dirname(fileURLToPath(import.meta.url));
const source=join(here,'../..');
const d=JSON.parse(readFileSync(join(source,'results/test_predictions.json')));
const references=JSON.parse(readFileSync(join(here,'sklearn-reference.json')));
const scores=d.proba[d.final];
const oldGuide=readFileSync(join(here,'../a5-1.html'),'utf8');
const oldContext={};vm.createContext(oldContext);
vm.runInContext(oldGuide.match(/<script id="math-engine">([\s\S]*?)<\/script>/)[1],oldContext);
let checks=0;
for(const expected of references){const got=classify(d.is_overdue,scores,expected.threshold);for(const key of ['tn','fp','fn','tp','precision','recall','f1','accuracy']){assert.ok(Math.abs(got[key]-expected[key])<1e-12,`${expected.threshold}: ${key}`);checks++;}const old=oldContext.a5Math.thresholdEval(scores,d.is_overdue,expected.threshold);for(const key of ['precision','recall','f1','accuracy'])assert.ok(Math.abs(old[key]-got[key])<1e-12,`old guide ${key}`);}
const manifest=JSON.parse(readFileSync(join(here,'source-manifest.json')));
assert.deepEqual(manifest.baseline,{...classify(d.is_overdue,scores,.5)});
for(const key of ['tp','fp','tn','fn'])assert.equal(manifest.baseline[key],manifest.reference.confusion[key]);
assert.equal(createHash('sha256').update(readFileSync(join(here,'../a5-1.html'))).digest('hex'),manifest.existingGuideSha256);
const html=readFileSync(join(here,'threshold.html'),'utf8');
assert.ok(!/<script[^>]+src=|<link[^>]+href=["']https?:|https?:\/\//i.test(html.replaceAll('http://www.w3.org/2000/svg','')),'standalone HTML has no remote dependencies');
const embedded=JSON.parse(html.match(/const DATA=(.*?);const P=/s)[1]);
assert.deepEqual(embedded,{model:d.final,labels:d.is_overdue,scores});
assert.ok(oldGuide.includes('id="ch04"'));
const rows=[.2,.5,.8].map(t=>({threshold:t,...classify(d.is_overdue,scores,t)}));
writeFileSync(join(here,'verification.json'),JSON.stringify({thresholds:references.length,numericalChecks:checks,sourceIntegrity:true,originalGuideLinked:true,originalGuideCalculationsMatch:true,standalone:true,rows},null,2));
console.log(`PASS: ${checks} numerical comparisons against scikit-learn; source, old guide and offline independence verified`);
console.table(rows);
