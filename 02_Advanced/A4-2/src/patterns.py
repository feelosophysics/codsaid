"""정보 추출용 정규표현식 모음.

모든 패턴은 re.VERBOSE로 쓰고 줄마다 의도와 매칭 범위를 주석으로 단다.

작성 원칙
- \\d, \\w, \\b를 쓰지 않는다. Python의 str 패턴에서 이 셋은 유니코드 기준이다.
  그래서 \\d는 전각·아라비아 숫자까지, \\w와 \\b는 한글까지 단어 문자로 본다.
  "test@x.com입니다"에서 \\b는 com과 입 사이를 경계로 보지 않는다.
  [0-9], [A-Za-z]처럼 범위를 직접 적으면 이런 일이 없다.
  같은 패턴을 학습 자료(HTML)의 JavaScript에서도 똑같이 동작시킬 수 있다.
- 패턴 앞뒤를 lookbehind (?<!...) / lookahead (?!...)로 막는다.
  더 긴 숫자열이나 단어의 일부를 잘라 오지 않게 하기 위해서다.
- 패턴은 후보를 찾는 데까지만 한다. 날짜가 실제로 있는 날인지, 한글 수사가 숫자로
  해석되는지 같은 의미 검증은 normalize.py가 맡는다. 정규식으로 윤년까지 검사하면
  읽을 수 없는 패턴이 된다.
- 리터럴 공백은 [ ]로, '#'는 \\#로 쓴다. VERBOSE 모드는 공백과 '#' 뒤를 무시하기 때문이다.
"""
