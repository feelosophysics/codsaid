"""
[파이썬 문법 및 컴퓨터 과학(CS) 개념 설명]

1. `import` 구문
   - 파이썬에서 제공하는 표준 라이브러리(Standard Library)나 설치된 외부 라이브러리(Third-party Library)를 현재 파일 안으로 가져와서 사용하겠다는 선언입니다.
   - `os`: 운영체제(OS, Operating System)에서 제공하는 기능(파일 경로 확인, 환경 변수 접근 등)을 호출할 수 있는 파이썬 내장 모듈입니다.
   - `yaml`: YAML Ain't Markup Language(YAML) 형식의 텍스트 데이터를 파이썬 딕셔너리(dictionary)나 리스트(list) 객체로 파싱하고 변환할 때 사용하는 외부 모듈입니다.

2. OS 관점에서의 파일과 입출력(I/O, Input/Output)
   - 프로그램이 파일에 있는 데이터를 읽으려면 운영체제에 '파일을 열어달라(Open)'고 요청해야 합니다. 이때 운영체제는 프로세스에게 파일에 대한 접근 권한이 담긴 '파일 디스크립터(File Descriptor)'라는 고유 식별 번호를 부여합니다.
   - 컴퓨터 시스템의 파일 디스크립터 개수는 한정되어 있으므로, 파일을 다 썼다면 반드시 '닫아(Close)'주어야 시스템 자원이 낭비(누수, Resource Leak)되지 않습니다.

3. 콘텍스트 매니저(Context Manager)와 `with`문
   - `with open(...) as f:` 구문은 파이썬이 제공하는 '콘텍스트 매니저' 문법입니다.
   - `with` 블록을 시작할 때 파일을 자동으로 열고(`__enter__` 메서드 실행), 블록이 끝나거나 내부에서 에러가 발생하여 블록을 빠져나갈 때 파일을 자동으로 닫아줍니다(`__exit__` 메서드 실행).
   - 이를 통해 개발자가 명시적으로 `f.close()`를 작성하지 않아도 자원 해제를 보장하여 자원 누수 문제를 예방합니다.

4. 캐릭터 인코딩(Character Encoding) - UTF-8
   - 컴퓨터는 원래 0과 1의 숫자만 이해합니다. 문자('가', 'A' 등)를 컴퓨터가 이해할 수 있는 2진수 데이터로 매핑하는 규칙을 '인코딩(Encoding)'이라고 합니다.
   - `utf-8`은 유니코드(Unicode)를 표현하는 대표적인 가변 길이 문자 인코딩 방식입니다. 전 세계의 거의 모든 문자를 표현할 수 있으며, 한글도 정상적으로 표현(한 글자당 3바이트로 처리)하기 위해 `encoding='utf-8'` 옵션을 지정해 파일에 접근합니다.

5. YAML 파일과 직렬화/역직렬화(Serialization/Deserialization)
   - 직렬화(Serialization)는 프로그램 내에 존재하는 객체(예: 파이썬의 dict)를 파일 저장이나 네트워크 전송이 가능하도록 바이트 스트림(문자열)으로 변환하는 것입니다.
   - 역직렬화(Deserialization)는 반대로 디스크에 저장된 텍스트/바이트 데이터를 프로그램의 메모리 상에 객체 구조로 복원하는 과정입니다.
   - `yaml.safe_load(f)`는 파일의 텍스트(YAML)를 역직렬화하여 파이썬의 딕셔너리 구조로 변환합니다. `safe_load`를 쓰는 이유는 임의의 파이썬 객체 코드가 실행되는 보안 취약점을 차단하고 순수한 데이터 구조만 안전하게 불러오기 위함입니다.

6. 가드 클로즈(Guard Clause) 혹은 얼리 리턴(Early Return)
   - 핵심 로직을 실행하기 전에 데이터의 유효성 검사나 예외적 케이스(설정 파일이 없는 경우 등)를 먼저 검사하여 조기에 함수를 종료(`return None`)시키는 코딩 기법입니다.
   - 이 기법을 사용하면 코드가 깊게 중첩(Nested `if-else`)되는 것을 막아주고, 메인 비즈니스 로직에만 집중할 수 있게 하여 가독성을 극대화합니다.
"""

# 팀 내 Git 커밋 및 PR 컨벤션 설정 파일(.ai-gitgen.yml)을 로드하는 모듈을 설명하는 모듈 수준의 Docstring
"""팀 내 Git 커밋 및 PR 컨벤션 설정 파일(.ai-gitgen.yml)을 로드하는 모듈입니다."""

import os  # 운영체제 상호작용(파일 존재 여부 확인 등)을 위해 파이썬 표준 라이브러리 os 임포트
import yaml  # YAML 형식의 텍스트 데이터를 분석(파싱)하기 위해 PyYAML 라이브러리 임포트

def load_convention():
    """프로젝트 루트에 있는 .ai-gitgen.yml 파일을 로드하여 설정을 반환합니다.
    
    설정 파일이 없거나 파일 구문 오류(Parsing Error) 등 예외가 발생할 시
    프로그램을 죽이지 않고 안전하게 None을 반환함으로써, 메인 흐름이 기본 규칙(컨벤션 없음)으로 동작하게 유도합니다.
    """
    
    # 불러올 설정 파일의 상대 경로 이름 문자열을 변수에 저장합니다.
    # 파일 이름 앞의 점(.)은 숨김 파일(Hidden File)을 의미하는 Unix/Linux 컨벤션입니다.
    config_file = 'ai-gitgen.yml'
    
    # 1. 데이터 유효성 검사 (Early Return / Guard Clause 적용)
    # os.path.exists() 함수는 지정된 경로에 실제 파일이나 디렉토리가 존재하는지 검사하여 True/False를 반환합니다.
    # 파일이 존재하지 않는 경우(!not) 더 이상 무의미한 I/O 연산을 진행하지 않고 조기에 None을 반환하며 종료합니다.
    if not os.path.exists(config_file):
        return None
        
    # 2. 로직 실행 및 예외 처리(try-except-finally 구조)
    try:
        # 'with' 문을 사용하여 파일을 읽기 모드('r' = read)로 엽니다.
        # 인코딩으로 'utf-8'을 지정하여 한글 주석이나 규칙 내용이 깨지지 않게 보장합니다.
        with open(config_file, 'r', encoding='utf-8') as f:
            # yaml.safe_load()를 호출하여 열려 있는 파일 객체 'f'의 텍스트 내용을 파싱합니다.
            # 정상 동작 시 파이썬의 중첩 딕셔너리(dict) 데이터 형식으로 변환된 결과가 config 변수에 할당됩니다.
            config = yaml.safe_load(f)
            
            # 파일 로드 성공 여부를 표준 출력(콘솔)을 통해 로그 메시지로 노출합니다.
            print("[INFO] .ai-gitgen.yml 컨벤션 파일을 성공적으로 불러왔습니다.")
            
            # 최종 변환된 딕셔너리 객체를 호출자(Caller)에게 반환합니다.
            return config
            
    # yaml 모듈 내에 정의된 YAML 파싱 관련 에러(문법 오류 등)를 캐치합니다.
    except yaml.YAMLError as exc:
        # YAML 구조적 오류(예: 들여쓰기 틀림, 잘못된 특수기호 사용 등)가 있을 경우 에러 내용을 콘솔에 상세히 안내합니다.
        print(f"[ERROR] 컨벤션 파일 파싱 오류: {exc}")
        # 오류가 나도 프로그램이 비정상 종료(Crash)되지 않도록 예외를 처리하고 None을 리턴하여 호출부에 알립니다.
        return None
        
    # 그 외 발생할 수 있는 모든 일반적인 시스템 에러(파일 접근 권한 오류, OS 수준 예외 등)를 포괄하여 감지합니다.
    except Exception as exc:
        # 예상치 못한 시스템적인 오류가 일어난 경우 발생 원인을 로깅합니다.
        print(f"[ERROR] 설정 파일을 읽는 중 알 수 없는 오류 발생: {exc}")
        # 예외를 던지지 않고 안전하게 None을 반환하여 시스템의 안정성(Robustness)을 확보합니다.
        return None
