"""
[파이썬 문법 및 컴퓨터 과학(CS) 개념 설명]

1. 클래스(Class)와 정적 속성(Class/Static Variable)
   - 파이썬에서 `class` 키워드는 새로운 객체(Object) 타입을 정의하는 틀을 만듭니다.
   - 클래스 내부에 정의되지만 메서드(함수) 바깥에 바로 선언된 변수(예: COMMIT_MESSAGE_PROMPT)는 '클래스 변수(Class Variable)'라고 부릅니다.
   - 인스턴스(instance, 예: obj = PromptTemplates())를 굳이 만들지 않고도 `PromptTemplates.COMMIT_MESSAGE_PROMPT`와 같이 클래스 이름을 통해 메모리에 직접 접근할 수 있습니다.
   - 이 방식은 전역 변수처럼 프로그램 전체에서 상수로 가져다 쓰고 싶을 때, 여러 변수를 논리적으로 그룹화(캡슐화, Encapsulation)하는 훌륭한 도구입니다.

2. 삼중 따옴표(Triple Quotes, `\"\"\"` 또는 `'''`)를 이용한 다중행 문자열(Multiline String)
   - 일반 따옴표(`"`, `'`)는 문자열을 한 줄 내에 작성해야 하지만, 삼중 따옴표는 줄바꿈(New line, `\n`)을 포함하여 여러 줄의 긴 문장을 그대로 입력할 수 있습니다.
   - 문자열 내에서 들여쓰기(tab, space)나 엔터(개행 문자)가 있는 그대로 유지됩니다.

3. 문자열 포맷팅(String Formatting) - 중괄호 `{}` 기법
   - 문자열 안에 `{status_text}`, `{diff_text}`처럼 중괄호를 넣고, 나중에 `.format(status_text=값1, diff_text=값2)`을 호출하면 중괄호 부분이 변수의 값으로 치환됩니다.
   - CS 원리: 템플릿 바인딩(Template Binding)으로, 정적인 레이아웃(틀)에 동적인 데이터(값)를 결합하여 최종 문자열을 합성해내는 효율적인 방법입니다.

4. 프롬프트 엔지니어링(Prompt Engineering)
   - 생성형 AI에게 원하는 출력 형식을 유도하기 위해 질문과 제약 조건을 세밀하게 설계하는 기법입니다.
   - LLM(대규모 언어 모델)은 이전 단어들을 바탕으로 다음 단어를 확률적으로 예측하는 메커니즘을 가집니다. 따라서 제약 조건이 모호하면 원치 않는 응답(예: "네, 커밋 메시지를 작성해 드릴게요!" 같은 부연 설명)이 포함될 수 있습니다.
   - 프롬프트 템플릿 하단에 "결과물만 출력해달라"는 명확한 제약 조건을 적는 것도 이러한 예측 범위를 좁히기 위함입니다.
"""

# AI API 호출 시 사용할 프롬프트 템플릿들을 보관하는 모듈을 설명하는 모듈 수준의 Docstring
"""AI API 호출 시 사용할 프롬프트 템플릿들을 보관하는 모듈입니다."""

class PromptTemplates:
    """AI API 호출 시 사용할 프롬프트 템플릿 상수를 정의하는 클래스입니다.
    
    모든 프롬프트는 static 속성(클래스 변수)으로 일괄 관리되어,
    객체를 생성하지 않고 클래스명 뒤에 점(.)을 찍어 바로 참조할 수 있습니다.
    """
    
    # Git 커밋 메시지 생성을 위한 정적 템플릿 문자열
    # 외부에서 .format(status_text=..., diff_text=...) 형식으로 호출되어 최종 프롬프트로 변환됩니다.
    COMMIT_MESSAGE_PROMPT = """다음은 Git 변경 사항입니다. 이를 바탕으로 규격에 맞는 커밋 메시지를 작성해주세요.

[Git Status]
{status_text}

[Git Diff]
{diff_text}

[요구사항]
1. 커밋 메시지는 한국어로 작성해주세요.
2. 커밋 제목 1줄은 필수로 포함해주세요. 제목은 50자 이내로 작성해주세요.
3. 커밋 본문에는 실제로 변경된 파일이나 모듈 명칭을 반드시 1~3개 명시해야 합니다.
4. 커밋 본문에는 이번 커밋의 핵심 변경 사항 1~2개를 반드시 불릿 포인트(-)로 구체적으로 작성해야 합니다. 절대 내용이 비어있는 빈 불릿('-')을 생성하지 마십시오.

[권장 출력 형식]
[커밋 제목] (예: feat: OO 기능 추가)

- 변경 파일: [실제 변경된 파일명 언급]
- 핵심 변경 사항: [무엇을 왜 변경했는지 1~2개 요약]"""

    # Pull Request(PR) 본문 작성을 위한 정적 템플릿 문자열
    # 동일하게 .format() 함수를 사용해 동적인 텍스트 값들과 매핑됩니다.
    PR_DRAFT_PROMPT = """다음은 Git 변경 사항입니다. 이를 바탕으로 Pull Request(PR) 초안을 작성해주세요.

[Git Status]
{status_text}

[Git Diff]
{diff_text}

[요구사항]
1. PR 초안은 한국어로 작성해주세요.
2. PR 제목 1줄을 먼저 적어주세요. 제목은 80자 이내로 작성해주세요.
3. 본문은 다음 섹션 헤더를 반드시 포함해야 합니다:
   ## Why (변경 배경)
   ## What (핵심 변경 사항)
   ## How to Test (테스트 방법)
4. 각 섹션에는 최소 1개 이상의 불릿 포인트(-)가 포함되어야 합니다."""
