-- -----------------------------------------------------------------------------
-- [Query 16] RENTAL 테이블의 status 컬럼에 인덱스 생성
-- -----------------------------------------------------------------------------
-- 설명: 대여 중('RENTED') 또는 연체 중('OVERDUE')인 도서를 필터링하는 조건 검색(Query 5 등)은
--       도서관 관리 프로그램에서 하루에도 수천 번씩 실행되는 핵심 비즈니스 로직입니다.
--       여기에 인덱스를 적용하여 극적인 속도 향상을 얻습니다.
--
-- 💡 인덱스의 원리 (B-Tree):
--   - 인덱스가 없으면 DB 엔진은 RENTAL 테이블 전체를 첫 행부터 끝 행까지 샅샅이 뒤지는 
--     **Full Table Scan(O(N))**을 수행합니다. 데이터가 100만 건이면 100만 번의 디스크 I/O가 생깁니다.
--   - `CREATE INDEX`를 실행하면 데이터베이스는 `status` 컬럼의 값을 오름차순 정렬된 
--     **B-Tree(Balanced Tree)** 구조로 별도 저장 공간에 구축합니다.
--   - 이 인덱스를 태우면 특정 상태를 찾기 위해 **O(log N)** 수준의 디스크 탐색만 수행하여
--     100만 건 중에서도 단 몇 번의 노드 이동으로 원하는 데이터를 즉시 찾아냅니다 (Index Range Scan).
-- -----------------------------------------------------------------------------
CREATE INDEX idx_rental_status ON RENTAL(status);
