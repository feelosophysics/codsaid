-- 본 파일은 데이터 모델링 요구사항을 완벽히 충족하며, 입문자가 SQL 엔진의 물리적/논리적 
-- 작동 메커니즘을 시각적, 수학적으로 이해할 수 있도록 "상상을 초월하는 깊이의 개념 해설 주석"을 동반합니다.
--
-- -----------------------------------------------------------------------------
-- 💡 SQL 문법의 비밀: 작성 순서 vs 실제 실행 순서 (Logical Query Processing)
-- 
-- 프로그래밍 코드는 위에서 아래로 순차 실행되지만, SQL 엔진은 작성된 순서대로 쿼리를 실행하지 않습니다!
-- [작성하는 순서]                       [RDBMS가 실제 실행하는 순서]
-- 5. SELECT 컬럼명                       1. FROM 테이블명 (+ JOIN으로 가상 테이블 병합)
-- 1. FROM 테이블명                       2. WHERE 필터링 조건
-- 2. WHERE 조건                          3. GROUP BY 그룹화할 컬럼
-- 3. GROUP BY 그룹할컬럼                  4. HAVING 그룹 필터링 조건
-- 4. HAVING 그룹조건                      5. SELECT 컬럼 계산 (이 시점에 별칭/Alias가 생성됨)
-- 6. ORDER BY 정렬기준                   6. DISTINCT 중복 제거
-- 7. LIMIT 개수제한                      7. ORDER BY 정렬
--                                        8. LIMIT 결과 행 개수 제한
-- 
-- ⚠️ 중요: ORDER BY에서만 SELECT에서 지정한 Alias(별명)를 쓸 수 있는 이유가 바로 이 실행 순서 때문입니다!
-- =============================================================================

-- 외래키 활성화 확인
PRAGMA foreign_keys = ON;


-- =============================================================================
-- PART A: 기본 조회 쿼리 (4개)
-- 목적: 단일 테이블에서 데이터를 필터링(WHERE), 정렬(ORDER BY), 제한(LIMIT)하는 기본기 습득
-- =============================================================================

-- -----------------------------------------------------------------------------
-- [Query 1] 전체 회원 목록 조회 (가입일이 오래된 순)
-- -----------------------------------------------------------------------------
-- 설명: 서비스 가입일을 기준으로 가입이 가장 빠른 회원부터 순서대로 나열합니다.
-- 작동 원리: 
--   1. FROM MEMBER: 회원 테이블 전체 행을 읽어들임.
--   2. SELECT: 지정한 id, name, email, join_date 컬럼 데이터만 투영(Projection).
--   3. ORDER BY join_date ASC: 날짜 컬럼을 오름차순(ASC)으로 정렬해 최종 반환.
SELECT id, name, email, join_date
FROM MEMBER
ORDER BY join_date ASC;


-- -----------------------------------------------------------------------------
-- [Query 2] 20,000원 이상인 고가 도서 목록 조회 (가격 내림차순 정렬)
-- -----------------------------------------------------------------------------
-- 설명: 책 가격이 20,000원 이상인 비싼 도서들을 찾아, 가격이 높은 순으로 정렬합니다.
-- 작동 원리:
--   1. FROM BOOK: 도서 테이블을 스캔함.
--   2. WHERE price >= 20000: 각 행을 순회하며 price 컬럼 값이 20000 미만인 행을 버림(수평 필터링).
--   3. SELECT id, title, price: 필터링을 통과한 행 중 필요한 컬럼만 추출.
--   4. ORDER BY price DESC: 가격 기준 내림차순(DESC, High to Low) 정렬.
SELECT id, title, author, price
FROM BOOK
WHERE price >= 20000
ORDER BY price DESC;


-- -----------------------------------------------------------------------------
-- [Query 3] 이메일 도메인이 '@example.com'인 회원 중 최근에 가입한 5명 조회
-- -----------------------------------------------------------------------------
-- 설명: 특정 이메일 형식을 갖춘 회원 중, 최근 가입자 5명만 제한하여 가져옵니다.
-- 작동 원리:
--   1. WHERE email LIKE '%@example.com': LIKE 연산자와 와일드카드 문자(%)를 사용하여
--      문자열 끝부분 패턴 매칭을 수행합니다. (%는 0개 이상의 임의의 문자열을 뜻함)
--   2. ORDER BY join_date DESC: 가장 최근에 가입한 사람(날짜가 큰 사람)부터 정렬합니다.
--   3. LIMIT 5: 정렬된 결과 셋에서 위에서부터 딱 5개의 레코드만 남기고 나머지는 잘라냅니다.
SELECT id, name, email, join_date
FROM MEMBER
WHERE email LIKE '%@example.com'
ORDER BY join_date DESC
LIMIT 5;


-- -----------------------------------------------------------------------------
-- [Query 4] 도서 카테고리 목록 조회 (이름 사전순)
-- -----------------------------------------------------------------------------
-- 설명: 등록되어 있는 모든 카테고리 이름을 가나다(사전) 순으로 조회합니다.
SELECT id, name
FROM CATEGORY
ORDER BY name ASC;



-- =============================================================================
-- PART B: 조인(JOIN) 조회 쿼리 (4개)
-- 목적: 외래키(FK)를 교량 삼아 흩어진 테이블의 정보를 관계 대수의 Join 연산으로 병합
-- =============================================================================

-- -----------------------------------------------------------------------------
-- [Query 5] 현재 대여 중 또는 연체 중인 도서와 대여한 회원 정보 결합 조회 (INNER JOIN)
-- -----------------------------------------------------------------------------
-- 설명: 도서관 입장에서 "지금 누가 어떤 책을 안 돌려주고 갖고 있는지" 파악하는 쿼리입니다.
-- 개념 (INNER JOIN, 내부 조인):
--   - 교집합 연산입니다. RENTAL 테이블의 member_id와 MEMBER 테이블의 id가 
--     일치하는 행들만 연결하고, 한쪽에만 존재하거나 짝이 없는 행은 결과에서 완전히 배제합니다.
-- 작동 원리:
--   1. FROM RENTAL r: 주 테이블 설정
--   2. INNER JOIN MEMBER m ON r.member_id = m.id: 
--      r의 member_id와 m의 id 컬럼이 같은 행끼리 가로로 결합. (O(N) 또는 인덱스 이용 시 O(1))
--   3. INNER JOIN BOOK b ON r.book_id = b.id:
--      결합된 가상 테이블에 다시 book_id를 기준으로 BOOK 테이블의 정보를 가로로 덧붙임.
--   4. WHERE r.status IN ('RENTED', 'OVERDUE'): 대여 중이거나 연체 중인 내역만 필터링.
SELECT 
    r.id AS rental_id,
    m.name AS member_name,
    b.title AS book_title,
    r.rental_date,
    r.status
FROM RENTAL r
INNER JOIN MEMBER m ON r.member_id = m.id
INNER JOIN BOOK b ON r.book_id = b.id
WHERE r.status IN ('RENTED', 'OVERDUE')
ORDER BY r.rental_date ASC;


-- -----------------------------------------------------------------------------
-- [Query 6] 특정 회원(이영희, ID=1)의 전체 대여 이력 조회 (INNER JOIN)
-- -----------------------------------------------------------------------------
-- 설명: 마이페이지 등에서 특정 사용자 한 명의 모든 대여 내역 및 책 정보를 조회할 때 사용합니다.
-- 작동 원리:
--   - SQL의 'ALIAS(별칭)' 사용: RENTAL을 `r`, BOOK을 `b`로 축약하여 쿼리 가독성을 높입니다.
--   - WHERE r.member_id = 1 조건을 인덱스 검색으로 빠르게 타격하여 해당 회원의 레코드만 조인 대상으로 삼습니다.
SELECT 
    r.id AS rental_id,
    b.title AS book_title,
    b.author AS book_author,
    r.rental_date,
    r.return_date,
    r.status
FROM RENTAL r
INNER JOIN BOOK b ON r.book_id = b.id
WHERE r.member_id = 1
ORDER BY r.rental_date DESC;


-- -----------------------------------------------------------------------------
-- [Query 7] 모든 책 목록과 그 책의 누적 대여 횟수 조회 (LEFT JOIN)
-- -----------------------------------------------------------------------------
-- 설명: 책의 인기도 통계를 낼 때, "한 번도 대여되지 않은 책"까지 포함하여 대여 횟수를 구합니다.
-- 개념 (LEFT OUTER JOIN, 왼쪽 외부 조인):
--   - 왼쪽 테이블(BOOK)의 모든 레코드를 무조건 보존합니다.
--   - 오른쪽 테이블(RENTAL)에 일치하는 대여 데이터가 없다면, RENTAL의 컬럼들은 전부 NULL로 채워서 출력합니다.
--   - 만약 그냥 INNER JOIN을 쓰면 대여가 0회인 책은 결과에서 증발해버립니다. (이를 방지!)
-- ⚠️ COUNT(r.id)의 디테일:
--   - COUNT(*)은 NULL을 포함한 행 개수를 세므로 대여 0회인 책도 1로 카운트됩니다.
--   - COUNT(r.id)는 r.id 컬럼 값이 NULL이 아닌 행의 개수만 세기 때문에 0회 대여된 책이 정확하게 '0'으로 집계됩니다!
SELECT 
    b.id AS book_id,
    b.title AS book_title,
    COUNT(r.id) AS total_rentals
FROM BOOK b
LEFT JOIN RENTAL r ON b.id = r.book_id
GROUP BY b.id, b.title
ORDER BY total_rentals DESC, b.title ASC;


-- -----------------------------------------------------------------------------
-- [Query 8] 모든 회원 목록과 그들의 현재 대여 도서 정보 조회 (LEFT JOIN)
-- -----------------------------------------------------------------------------
-- 설명: 대여 중인 책이 없는 회원(NULL)을 포함하여, 전체 회원이 현재 빌려 쓰고 있는 상태를 보여줍니다.
-- 작동 원리:
--   - MEMBER(왼쪽)의 10명 데이터를 전부 살려두고, RENTAL 테이블 중 상태가 'RENTED'나 'OVERDUE'인 건들만 연결합니다.
--   - ON 절의 다중 조건: r.member_id = m.id 뒤에 `AND r.status != 'RETURNED'` 조건을 추가하여
--     반납 완료된 과거 이력은 조인 연결 대상에서 제외하고, 오직 '현재 대여 중'인 관계만 시각화합니다.
SELECT 
    m.id AS member_id,
    m.name AS member_name,
    r.rental_date,
    b.title AS renting_book_title
FROM MEMBER m
LEFT JOIN RENTAL r ON m.id = r.member_id AND r.status IN ('RENTED', 'OVERDUE')
LEFT JOIN BOOK b ON r.book_id = b.id
ORDER BY m.id ASC;



-- =============================================================================
-- PART C: 집계 및 그룹화 쿼리 (3개)
-- 목적: 데이터를 특정 범주(GROUP BY)로 묶고 요약값(COUNT, SUM, AVG)을 계산
-- =============================================================================

-- -----------------------------------------------------------------------------
-- [Query 9] 카테고리별 도서 수 및 평균 도서 가격 (GROUP BY + COUNT + AVG)
-- -----------------------------------------------------------------------------
-- 설명: 각 카테고리(장르)에 책이 몇 권 등록되어 있고, 평균 정가는 얼마인지 산출합니다.
-- 작동 원리:
--   1. FROM BOOK b JOIN CATEGORY c: 도서와 카테고리를 붙임.
--   2. GROUP BY c.id, c.name: 동일한 카테고리 ID와 이름을 가진 레코드끼리 상자(Bucket)에 모음.
--   3. 집계 함수 계산:
--      - COUNT(b.id): 해당 상자에 속한 도서의 개수 카운트.
--      - AVG(b.price): 해당 상자에 속한 도서들의 가격 산술평균 계산. (ROUND 함수로 소수점 첫째 자리 반올림)
SELECT 
    c.name AS category_name,
    COUNT(b.id) AS book_count,
    ROUND(AVG(b.price), 1) AS average_price
FROM BOOK b
INNER JOIN CATEGORY c ON b.category_id = c.id
GROUP BY c.id, c.name
ORDER BY book_count DESC;


-- -----------------------------------------------------------------------------
-- [Query 10] 회원별 누적 대여 횟수 및 총 연체료 가치 합산 (GROUP BY + COUNT + SUM)
-- -----------------------------------------------------------------------------
-- 설명: 각 회원별로 누적 대여를 몇 번 했고, 빌려간 도서 가격의 합계(SUM)가 얼마인지 합산해 우수 회원을 식별합니다.
-- 작동 원리:
--   - RENTAL과 BOOK을 조인하여 빌려간 책들의 가격 정보를 가져옵니다.
--   - 회원(m.id) 단위로 그룹화하여 카운팅과 합계 연산을 동시 수행합니다.
SELECT 
    m.id AS member_id,
    m.name AS member_name,
    COUNT(r.id) AS total_rental_count,
    SUM(b.price) AS total_rented_book_value
FROM MEMBER m
INNER JOIN RENTAL r ON m.id = r.member_id
INNER JOIN BOOK b ON r.book_id = b.id
GROUP BY m.id, m.name
ORDER BY total_rental_count DESC;


-- -----------------------------------------------------------------------------
-- [Query 11] 대여 상태별 대여 건수 집계 및 요약 (GROUP BY + COUNT)
-- -----------------------------------------------------------------------------
-- 설명: 도서관 시스템 전체에서 반납 완료(RETURNED), 대여 중(RENTED), 연체(OVERDUE)인 대여 건의 누적 수치를 집계합니다.
--       현재 관리 중인 도서 유통 상태의 거시적 요약 지표를 제공합니다.
SELECT 
    status,
    COUNT(*) AS count
FROM RENTAL
GROUP BY status
ORDER BY count DESC;



-- =============================================================================
-- PART D: 서브쿼리(Subquery) 조회 (1개)
-- 목적: 쿼리 안에 또 다른 쿼리를 삽입하여 동적으로 계산된 결과를 메인 쿼리의 조건으로 활용
-- =============================================================================

-- -----------------------------------------------------------------------------
-- [Query 12] 전체 도서 평균 가격보다 비싼 명품 도서 목록 (비교 서브쿼리)
-- -----------------------------------------------------------------------------
-- 설명: 도서관이 보유한 책의 전체 평균 가격을 구하고, 그 평균보다 비싼 책들만 조회합니다.
-- 작동 원리:
--   - [서브쿼리 부분] (SELECT AVG(price) FROM BOOK) 이 먼저 독립 실행되어 단 하나의 스칼라 값(예: 21650.0)을 리턴합니다.
--   - [메인 쿼리 부분] WHERE price > 21650.0 을 수행하여 조건에 만족하는 책만 걸러냅니다.
--   - 하드코딩 방식(평균 가격을 사람이 계산해 21650을 직접 적어 넣는 방식)과 달리, 신규 도서가 추가되어 평균 가격이 변동될 때마다 동적으로 실시간 반영되는 극도의 유연성을 가집니다.
SELECT id, title, price, author
FROM BOOK
WHERE price > (SELECT AVG(price) FROM BOOK)
ORDER BY price DESC;


-- -----------------------------------------------------------------------------
-- [Query 13] 도서를 단 한 번도 대여한 적 없는 휴면 회원 목록 (NOT EXISTS 서브쿼리)
-- -----------------------------------------------------------------------------
-- 설명: 가입만 하고 서비스를 이용하지 않은 회원을 추출하여 마케팅 대상자로 선정할 때 사용합니다.
-- 작동 원리 (NOT EXISTS):
--   - 메인 쿼리의 각 MEMBER 행(m)에 대해 서브쿼리가 작동합니다.
--   - RENTAL 테이블을 뒤져서 현재 돌고 있는 회원(m.id)과 같은 member_id가 존재하는지 확인합니다.
--   - 단 한 건도 매칭되지 않는(EXISTS의 결과가 거짓인) 회원 정보만 최종 리턴합니다.
--   - LEFT JOIN 후 NULL을 찾는 방식보다, 엔진 레벨에서 얼리 익스exit(Early Exit - 매칭되는 게 한 개라도 나오면 탐색을 즉시 멈춤)이 작동하여 성능 최적화에 탁월합니다.
SELECT id, name, email, join_date
FROM MEMBER m
WHERE NOT EXISTS (
    SELECT 1 
    FROM RENTAL r 
    WHERE r.member_id = m.id
);



-- =============================================================================
-- PART E: 데이터 수정 및 삭제 (2개)
-- 목적: 테이블의 기존 데이터를 조작하고 데이터 무결성이 훼손되지 않도록 트랜잭션 관리
-- =============================================================================

-- -----------------------------------------------------------------------------
-- [Query 14] 특정 대여 기간이 지난 대여 건을 'OVERDUE'(연체) 상태로 일괄 업데이트
-- -----------------------------------------------------------------------------
-- 설명: 대여일로부터 14일이 경과했으나 아직 반납되지 않은(return_date IS NULL) 책들의 상태를
--       일괄적으로 'OVERDUE'로 강제 갱신합니다.
-- SQL 기본: UPDATE 테이블명 SET 컬럼=값 WHERE 조건;
-- 작동 원리:
--   - julianday('2026-05-24') - julianday(rental_date) 연산은 두 날짜 사이의 일수 차이를 계산합니다.
--     (오늘 시점인 '2026-05-24'를 가상 현재일로 적용)
--   - 차이가 14일을 초과하고 반납일이 기록되지 않은 행만 찾아 상태를 변경합니다.
UPDATE RENTAL
SET status = 'OVERDUE'
WHERE return_date IS NULL 
  AND status = 'RENTED'
  AND (julianday('2026-05-24') - julianday(rental_date)) > 14;


-- -----------------------------------------------------------------------------
-- [Query 15] 회원 정보 삭제를 통한 CASCADE 작동 테스트 (임시 회원 11번 추가 후 삭제)
-- -----------------------------------------------------------------------------
-- 설명: 외래키 제약조건인 `ON DELETE CASCADE`가 하위 데이터(RENTAL)를 실제로 어떻게 
--       자동으로 청소해주는지 라이브로 목격하는 교육용 쿼리입니다.
--
-- 💡 동작 시나리오:
